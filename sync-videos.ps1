<#
.SYNOPSIS
    Piyush Yadav Portfolio - Automated Video Folder Sync Script (PowerShell)
.DESCRIPTION
    Scans a user-provided video folder, copies files to assets/videos, and generates
    live project data for the portfolio.
.EXAMPLE
    .\sync-videos.ps1 -FolderPath "C:\MyVideos\PiyushEdits"
#>

param(
    [Parameter(Mandatory=$false, Position=0)]
    [string]$FolderPath
)

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $FolderPath) {
    Write-Host "`n=======================================================" -ForegroundColor Cyan
    Write-Host "[SYNC] PIYUSH YADAV VIDEO PORTFOLIO SYNC (2026)" -ForegroundColor Yellow
    Write-Host "=======================================================" -ForegroundColor Cyan
    $FolderPath = Read-Host "Enter the path of your video folder"
}

$FolderPath = $FolderPath.Trim("'`"")

if (-not (Test-Path $FolderPath)) {
    Write-Host "`n[ERROR] Folder not found at: $FolderPath" -ForegroundColor Red
    exit 1
}

$TargetDir = Join-Path $ScriptDir "assets\videos"
if (-not (Test-Path $TargetDir)) {
    New-Item -ItemType Directory -Path $TargetDir -Force | Out-Null
}

$Extensions = @("*.mp4", "*.mov", "*.webm", "*.m4v", "*.mkv", "*.avi")
$VideoFiles = Get-ChildItem -Path $FolderPath -Include $Extensions -Recurse -File

if ($VideoFiles.Count -eq 0) {
    Write-Host "`n[!] No video files found in: $FolderPath" -ForegroundColor Yellow
    Write-Host "[!] Tip: You can also use the in-browser folder picker by clicking 'SYNC VIDEOS' in index.html.`n" -ForegroundColor Gray
    exit 0
}

Write-Host "`n[OK] Found $($VideoFiles.Count) video files. Syncing to portfolio..." -ForegroundColor Green

$SyncedProjects = @()
$Index = 1

foreach ($file in $VideoFiles) {
    $SafeName = ($file.Name -replace '[^a-zA-Z0-9_\-\.]', '_')
    $DestFile = Join-Path $TargetDir $SafeName
    
    Write-Host "  [$Index/$($VideoFiles.Count)] Copying $($file.Name) -> assets/videos/$SafeName" -ForegroundColor Gray
    if (-not (Test-Path $DestFile) -or ((Get-Item $DestFile).Length -ne $file.Length)) {
        Copy-Item -Path $file.FullName -Destination $DestFile -Force
    }

    # Category heuristic
    $Lower = $file.Name.ToLower()
    $Cat = "commercial"
    $CatLabel = "Commercial & Ads"
    $Aspect = "16:9"

    if ($Lower -match "reel|short|tiktok|vertical|9x16|9_16") {
        $Cat = "reels"
        $CatLabel = "9:16 Shorts & Reels"
        $Aspect = "9:16"
    } elseif ($Lower -match "music|song|mv|beat|track") {
        $Cat = "music"
        $CatLabel = "Music Videos"
        $Aspect = "2.39:1"
    } elseif ($Lower -match "vfx|cgi|motion|3d|aftereffects") {
        $Cat = "vfx"
        $CatLabel = "VFX & Motion Design"
        $Aspect = "16:9"
    }

    $Title = $file.BaseName -replace '[_\-\.]+', ' '
    $Title = (Get-Culture).TextInfo.ToTitleCase($Title)

    $Project = [PSCustomObject]@{
        id = "local-$Index"
        title = $Title.ToUpper()
        subtitle = "Piyush Yadav Edit • $CatLabel"
        category = $Cat
        categoryLabel = $CatLabel
        client = "Client Work // Piyush Yadav Archive"
        year = "2026"
        duration = "01:00"
        aspectRatio = $Aspect
        resolution = "4K UHD • Master"
        role = "Lead Editor • Colorist • Sound Design"
        software = @("DaVinci Resolve", "Premiere Pro", "After Effects")
        metrics = "Master Timeline Delivery"
        description = "Custom edit project '$Title', cut and graded by Piyush Yadav."
        videoSrc = "./assets/videos/$SafeName"
        previewSrc = "./assets/videos/$SafeName"
        poster = ""
        isLocal = $true
        featured = ($Index -le 4)
    }

    $SyncedProjects += $Project
    $Index++
}

# Output JS for instant zero-server browser loading
$JsonData = $SyncedProjects | ConvertTo-Json -Depth 5
$JsPath = Join-Path $ScriptDir "assets\user-videos.js"
$JsContent = "/* Auto-generated by sync-videos.ps1 */`nwindow.SYNCED_USER_VIDEOS = $JsonData;`n"
[System.IO.File]::WriteAllText($JsPath, $JsContent, [System.Text.Encoding]::UTF8)

Write-Host "`n=======================================================" -ForegroundColor Cyan
Write-Host "[SUCCESS] $($SyncedProjects.Count) VIDEOS SYNCED FOR PIYUSH YADAV!" -ForegroundColor Green
Write-Host "👉 Refresh index.html in your browser to view your edits live!" -ForegroundColor Yellow
Write-Host "=======================================================`n" -ForegroundColor Cyan
